# -*- coding: utf-8 -*-
"""Builds js/works.js — the museum's copy of each exhibited work's dossier.

The portfolio's data.js is the source of truth (it is regenerated from the
workbook by gen_data.py). The museum shows seven of those works, so this pulls
the fields its detail window needs and rewrites every asset path to be relative
to the museum root, which is one level above the site.

Skills and tags are deliberately not carried over: the exhibit card shows the
work's output, its technique and its evidence, never a skills list.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.join(HERE, "..", "..", "site", "assets", "js", "data.js")
OUT = os.path.join(HERE, "..", "..", "js", "works.js")

# The museum hangs these seven; matched by name against the site's projects.
EXHIBITED = ["FixProof", "CSE-CIC-IDS2018", "Litmus", "ESI Wiki",
             "Cisco ISE", "GameVerse Academy", "raxag"]


def main():
    src = open(SITE, encoding="utf-8").read()
    site = json.loads(src[src.index("{"):src.rindex("}") + 1])
    by_name = {p["name"]: p for p in site["projects"]}

    works = {}
    for name in EXHIBITED:
        p = by_name[name]
        base = "site/assets/img/%s/" % p["id"]
        links = dict(p.get("links") or {})
        sample = p.get("sample")
        if sample:
            sample = dict(sample)
            sample["url"] = ("https://drive.google.com/uc?export=download&id="
                             + sample["id"])
        works[name] = {
            "output": p.get("output", ""),
            "year": p.get("year", ""),
            "kind": p.get("kind", ""),
            "org": p.get("org", ""),
            "links": links,
            "sample": sample,
            "media": {
                "hero": base + p["hero"],
                "images": [base + f for f in p.get("images", [])],
                "video": ("site/assets/video/" + p["video"]) if p.get("video") else "",
            },
            "stats": p.get("stats", []),
        }

    js = ("// Generated by tools/sitebuild/gen_works.py — do not edit by hand.\n"
          "window.WORKS = " + json.dumps(works, ensure_ascii=False, indent=1) + ";\n"
          # The gallery door only offers the professional channels: the room is a
          # portfolio piece, not a link farm.
          "window.CONTACT = " + json.dumps({
              k: site["contact"][k] for k in
              ("name", "role", "location", "email_esi", "github", "linkedin")
          }, ensure_ascii=False, indent=1) + ";\n")
    open(OUT, "w", encoding="utf-8").write(js)

    print("works:", len(works))
    for name, w in works.items():
        print("  %-18s %-14s %2d imgs  links=%s  sample=%s" % (
            name, w["output"], len(w["media"]["images"]),
            ",".join(w["links"]) or "-", "yes" if w["sample"] else "-"))


if __name__ == "__main__":
    main()
